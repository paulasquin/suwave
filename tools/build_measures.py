"""Build js/data/measures.js: the drift-speed / wind-speed points of the 2017 spreadsheet
"Coefficients de déplacement" and the drift speed of the three wings on 16 August 2017.

    python3 -I tools/build_measures.py ~/scratch/suwave-src > js/data/measures.js
"""
import json, math, sys, pathlib, re
src = pathlib.Path(sys.argv[1]).expanduser()

# "Coefficients de déplacement" (Drive, 10 Sept 2017): session, wind m/s, drift m/s.
COEFS = [
    ("2 août · #2 matin", "2 Aug · #2 morning", 2, 0.11),
    ("2 août · #2 après-midi", "2 Aug · #2 afternoon", 3, 0.093),
    ("2 août · #4 session 1", "2 Aug · #4 session 1", 3, 0.11),
    ("2 août · #4 session 2", "2 Aug · #4 session 2", 3, 0.12),
    ("16 août · #2", "16 Aug · #2", 6, 0.283),
    ("16 août · #3", "16 Aug · #3", 6, 0.298),
    ("16 août · #4", "16 Aug · #4", 6, 0.327),
    ("29 août · #2", "29 Aug · #2", 1, 0.059772),
    ("29 août · #3", "29 Aug · #3", 1, 0.083322),
    ("29 août · #4", "29 Aug · #4", 1, 0.092508),
]
# Drift speed over 50 s windows (as in the 2017 Matlab analysis), from the lake tracks.
lakes = json.loads(re.search(r"export const LAKES = (.*);", open("js/data/lakes.js").read()).group(1))
raw = json.load(open(src / "tracks/raw.json"))
series = {}
for tr in lakes["montjoie"]["tracks"]:
    folder = f"deriveDrone_{tr['wing'][1]}_Standard_2017-08-16-pm"
    pts = [p for p in raw[folder] if tr["start"] - 0.6 <= p[0] <= tr["start"] + tr["duration"] + 0.6]
    lat0 = pts[0][1]
    kx, ky = 111320 * math.cos(math.radians(lat0)), 110574
    out = []
    for i in range(0, len(pts) - 50, 50):
        a, b = pts[i], pts[i + 50]
        d = math.hypot((b[2] - a[2]) * kx, (b[1] - a[1]) * ky)
        out.append([round((a[0] - pts[0][0]) / 60, 2), round(d / (b[0] - a[0]), 3)])
    series[tr["wing"]] = out
print("// Generated by tools/build_measures.py from the 2017 spreadsheet and the PX4 drift logs.")
print("export const COEFS = " + json.dumps([{"fr": a, "en": b, "wind": w, "drift": v} for a, b, w, v in COEFS], ensure_ascii=False) + ";")
print("export const SPEED_16AUG = " + json.dumps(series, separators=(",", ":")) + ";")
